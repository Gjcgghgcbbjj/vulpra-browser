#!/usr/bin/env python3
"""Generate Xcode and Swift build identity inputs from one JSON owner."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import sys


ROOT = Path(__file__).resolve().parents[2]
MANIFEST = ROOT / "Configuration/build-identity.json"
XCCONFIG = ROOT / "Configuration/BuildIdentity.generated.xcconfig"
SWIFT = ROOT / "App/Build/VulpraBuildIdentity.swift"
FIELDS = ("marketingVersion", "buildVersion", "developmentLanguage", "uiFingerprint")


def load_identity() -> dict[str, str]:
    value = json.loads(MANIFEST.read_text(encoding="utf-8"))
    if value.get("schemaVersion") != 1:
        raise ValueError("unsupported build identity schema")
    for field in FIELDS:
        item = value.get(field)
        if not isinstance(item, str) or not item or re.search(r"[\r\n]", item):
            raise ValueError(f"invalid build identity field: {field}")
    if not re.fullmatch(r"[0-9]+(?:\.[0-9]+){2}", value["marketingVersion"]):
        raise ValueError("marketingVersion must use major.minor.patch")
    if not value["buildVersion"].isdigit():
        raise ValueError("buildVersion must be numeric")
    return value


def render_xcconfig(value: dict[str, str]) -> str:
    return (
        "// Generated by Tools/Build/generate-build-identity.py. Do not edit.\n"
        f"CURRENT_PROJECT_VERSION = {value['buildVersion']}\n"
        f"MARKETING_VERSION = {value['marketingVersion']}\n"
        f"DEVELOPMENT_LANGUAGE = {value['developmentLanguage']}\n"
        f"VULPRA_UI_FINGERPRINT = {value['uiFingerprint']}\n"
    )


def render_swift(value: dict[str, str]) -> str:
    return (
        "import Foundation\n\n"
        "// Generated by Tools/Build/generate-build-identity.py. Do not edit.\n"
        "enum VulpraBuildIdentity {\n"
        f"    static let uiFingerprint = \"{value['uiFingerprint']}\"\n"
        f"    static let marketingVersion = \"{value['marketingVersion']}\"\n"
        f"    static let buildVersion = \"{value['buildVersion']}\"\n"
        "}\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--print", choices=FIELDS)
    args = parser.parse_args()
    try:
        value = load_identity()
    except (OSError, ValueError, json.JSONDecodeError) as error:
        print(f"build-identity-error: {error}", file=sys.stderr)
        return 1
    if args.print:
        print(value[args.print])
        return 0
    outputs = {XCCONFIG: render_xcconfig(value), SWIFT: render_swift(value)}
    if args.check:
        stale = [str(path.relative_to(ROOT)) for path, content in outputs.items()
                 if not path.is_file() or path.read_text(encoding="utf-8") != content]
        if stale:
            print(f"build-identity-error: stale generated files: {', '.join(stale)}", file=sys.stderr)
            return 1
        print("build-identity-ok")
        return 0
    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    print("build-identity-generated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
